/** The SVG document of an icon with no fill (the tile colors it with a CSS mask), or null for an unknown key. */
export function iconSvg(key: string): string | null {
  // Object.hasOwn keeps names such as "constructor" out of the lookup.
  if (!Object.hasOwn(PATHS, key)) return null
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path d="${PATHS[key as IconKey]}"/></svg>`
}
