import { describe, expect, test } from 'bun:test'
import {
  actionSteps,
  actionTitle,
  COMPOSE_LABELS,
  composeErrorLine,
  configCheckArgv,
  createLineSplitter,
  createRunReader,
  encodeRunEvent,
  firstLines,
  groupProjects,
  isGeneratedConfig,
  logsArgv,
  parseComposeLogLine,
  parseConfigFiles,
  parseRunBody,
  parseRunEvent,
  PROJECT_NAME,
} from './compose'

const labels = (project: string, service: string, extra: Record<string, string> = {}) => ({
  [COMPOSE_LABELS.project]: project,
  [COMPOSE_LABELS.service]: service,
  ...extra,
})

describe('parseConfigFiles', () => {
  test('splits the comma-separated label into paths', () => {
    expect(parseConfigFiles('/a/compose.yaml, /b/override.yaml')).toEqual(['/a/compose.yaml', '/b/override.yaml'])
  })

  test('an empty or missing label gives no files', () => {
    expect(parseConfigFiles(undefined)).toEqual([])
    expect(parseConfigFiles('')).toEqual([])
    expect(parseConfigFiles(' , ')).toEqual([])
  })
})

describe('groupProjects', () => {
  test('containers without a project label are not projects', () => {
    expect(groupProjects([{ labels: {}, running: true, isSelf: false }])).toEqual([])
  })

  test('counts running and total, and lists the services sorted and unique', () => {
    const dir = { [COMPOSE_LABELS.workingDir]: '/srv/app', [COMPOSE_LABELS.configFiles]: '/srv/app/compose.yaml' }
    const projects = groupProjects([
      { labels: { ...labels('shop', 'web', dir) }, running: true, isSelf: false },
      { labels: { ...labels('shop', 'db', dir) }, running: false, isSelf: false },
      { labels: { ...labels('shop', 'web', dir) }, running: true, isSelf: false },
    ])
    expect(projects).toEqual([
      {
        name: 'shop',
        workingDir: '/srv/app',
        configFiles: ['/srv/app/compose.yaml'],
        services: ['db', 'web'],
        running: 2,
        total: 3,
        containsSelf: false,
      },
    ])
  })

  test('the first container that has the folder and the files supplies them', () => {
    const projects = groupProjects([
      { labels: labels('app', 'api'), running: true, isSelf: false },
      {
        labels: labels('app', 'worker', {
          [COMPOSE_LABELS.workingDir]: '/x',
          [COMPOSE_LABELS.configFiles]: '/x/a.yaml,/x/b.yaml',
        }),
        running: true,
        isSelf: false,
      },
    ])
    expect(projects[0]?.workingDir).toBe('/x')
    expect(projects[0]?.configFiles).toEqual(['/x/a.yaml', '/x/b.yaml'])
  })

  test('flags a project that holds the container pow/dock runs in', () => {
    const projects = groupProjects([
      { labels: labels('powdock', 'app'), running: true, isSelf: true },
      { labels: labels('powdock', 'db'), running: true, isSelf: false },
    ])
    expect(projects[0]?.containsSelf).toBe(true)
  })

  test('projects are sorted by name', () => {
    const names = groupProjects([
      { labels: labels('zeta', 'a'), running: true, isSelf: false },
      { labels: labels('alpha', 'a'), running: true, isSelf: false },
    ]).map((project) => project.name)
    expect(names).toEqual(['alpha', 'zeta'])
  })
})

describe('isGeneratedConfig', () => {
  test('a file in a .generated folder is generated, whatever it says', () => {
    expect(isGeneratedConfig('/home/x/.generated/app.yaml', 'services:')).toBe(true)
  })

  test('the first lines that say generated or DO NOT EDIT mark a file', () => {
    expect(isGeneratedConfig('/srv/app/compose.yaml', '# Generated by tool\nservices:')).toBe(true)
    expect(isGeneratedConfig('/srv/app/compose.yaml', '# do not edit this file\n')).toBe(true)
  })

  test('a hand-written file is not generated, and an unreadable one is judged by its path only', () => {
    expect(isGeneratedConfig('/srv/app/compose.yaml', 'services:\n  web:\n    image: nginx')).toBe(false)
    expect(isGeneratedConfig('/srv/app/compose.yaml', null)).toBe(false)
  })

  test('firstLines keeps only the first lines', () => {
    expect(firstLines('a\nb\nc\nd\ne\nf\ng', 5)).toBe('a\nb\nc\nd\ne')
  })
})

describe('actionSteps update-service', () => {
  test('pulls one service, then starts it again, and runs nothing without a service', () => {
    const files = ['/srv/app/compose.yaml']
    const prefix = ['docker', 'compose', '-p', 'shop', '-f', '/srv/app/compose.yaml']
    expect(actionSteps('shop', files, 'update-service', false, 'web')).toEqual([
      [...prefix, 'pull', 'web'],
      [...prefix, 'up', '-d', 'web'],
    ])
    expect(actionSteps('shop', files, 'update-service', false, null)).toEqual([])
  })
})

describe('actionSteps', () => {
  const name = 'shop'
  const files = ['/srv/app/compose.yaml', '/srv/app/override.yaml']
  const prefix = ['docker', 'compose', '-p', 'shop', '-f', files[0], '-f', files[1]]

  test('up is one step: up -d --remove-orphans', () => {
    expect(actionSteps(name, files, 'up', false)).toEqual([[...prefix, 'up', '-d', '--remove-orphans']])
  })

  test('stop and restart are one step each', () => {
    expect(actionSteps(name, files, 'stop', false)).toEqual([[...prefix, 'stop']])
    expect(actionSteps(name, files, 'restart', false)).toEqual([[...prefix, 'restart']])
  })

  test('pull & update is pull, then up -d', () => {
    expect(actionSteps(name, files, 'pull', false)).toEqual([
      [...prefix, 'pull'],
      [...prefix, 'up', '-d', '--remove-orphans'],
    ])
  })

  test('down removes volumes only when asked', () => {
    expect(actionSteps(name, files, 'down', false)).toEqual([[...prefix, 'down']])
    expect(actionSteps(name, files, 'down', true)).toEqual([[...prefix, 'down', '--volumes']])
  })

  test('a project without files still names the project', () => {
    expect(actionSteps(name, [], 'up', false)).toEqual([
      ['docker', 'compose', '-p', 'shop', 'up', '-d', '--remove-orphans'],
    ])
  })

  test('the title names the command the user sees', () => {
    expect(actionTitle('up', false)).toBe('docker compose up')
    expect(actionTitle('update-service', false, 'web')).toBe('docker compose pull web, then up -d web')
    expect(actionTitle('down', true)).toBe('docker compose down --volumes')
    expect(actionTitle('pull', false)).toBe('docker compose pull, then up')
  })
})

describe('logsArgv', () => {
  test('follows the logs of every service with the tail, colors off and timestamps on', () => {
    expect(logsArgv('shop', ['/srv/app/compose.yaml'], 200)).toEqual([
      'docker',
      'compose',
      '-p',
      'shop',
      '-f',
      '/srv/app/compose.yaml',
      'logs',
      '-f',
      '--tail=200',
      '--no-color',
      '--timestamps',
    ])
  })
})

describe('parseRunBody', () => {
  test('accepts each action', () => {
    for (const action of ['up', 'stop', 'restart', 'pull', 'down'] as const) {
      expect(parseRunBody({ action })).toEqual({ ok: true, action, volumes: false, service: null })
    }
  })

  test('volumes is allowed only for down', () => {
    expect(parseRunBody({ action: 'down', volumes: true })).toEqual({
      ok: true,
      action: 'down',
      volumes: true,
      service: null,
    })
    const refused = parseRunBody({ action: 'up', volumes: true })
    expect(refused.ok).toBe(false)
  })

  test('update-service needs one service name, and service applies to nothing else', () => {
    expect(parseRunBody({ action: 'update-service', service: 'web' })).toEqual({
      ok: true,
      action: 'update-service',
      volumes: false,
      service: 'web',
    })
    expect(parseRunBody({ action: 'update-service' }).ok).toBe(false)
    expect(parseRunBody({ action: 'update-service', service: '-x' }).ok).toBe(false)
    expect(parseRunBody({ action: 'update-service', service: 'a b' }).ok).toBe(false)
    expect(parseRunBody({ action: 'up', service: 'web' }).ok).toBe(false)
  })

  test('refuses unknown actions, unknown fields and other shapes', () => {
    expect(parseRunBody({ action: 'rm -rf' }).ok).toBe(false)
    expect(parseRunBody({ action: 'up', dir: '/' }).ok).toBe(false)
    expect(parseRunBody({ action: 'up', volumes: 'yes' }).ok).toBe(false)
    expect(parseRunBody(null).ok).toBe(false)
    expect(parseRunBody(['up']).ok).toBe(false)
    expect(parseRunBody({}).ok).toBe(false)
  })
})

describe('parseComposeLogLine', () => {
  test('splits the service and the timestamp off a line', () => {
    expect(parseComposeLogLine('web-1  | 2026-11-24T10:00:00.123456789Z tick')).toEqual({
      service: 'web-1',
      t: '2026-11-24T10:00:00.123456789Z',
      m: 'tick',
    })
  })

  test('a separator in the message stays in the message', () => {
    expect(parseComposeLogLine('db-1 | a | b').m).toBe('a | b')
    expect(parseComposeLogLine('db-1 | a | b').service).toBe('db-1')
  })

  test('a line without a service prefix keeps its whole text', () => {
    expect(parseComposeLogLine('plain text | here')).toEqual({ service: null, t: null, m: 'plain text | here' })
    expect(parseComposeLogLine('no separator')).toEqual({ service: null, t: null, m: 'no separator' })
  })
})

describe('line splitter and run events', () => {
  test('a line split across two pieces comes out whole', () => {
    const splitter = createLineSplitter()
    expect(splitter.push('one\ntw')).toEqual(['one'])
    expect(splitter.push('o\r\nthree')).toEqual(['two'])
    expect(splitter.flush()).toEqual(['three'])
  })

  test('encoded events come back the same, and bad lines are dropped', () => {
    const reader = createRunReader()
    const text = encodeRunEvent({ s: 'out', m: 'Pulling' }) + encodeRunEvent({ s: 'err', m: 'warn' }) + '\nnot json\n'
    expect(reader.push(text)).toEqual([
      { s: 'out', m: 'Pulling' },
      { s: 'err', m: 'warn' },
    ])
    expect(reader.push(encodeRunEvent({ done: true, code: 0 }))).toEqual([{ done: true, code: 0 }])
  })

  test('parseRunEvent refuses shapes it does not know', () => {
    expect(parseRunEvent('{"s":"other","m":"x"}')).toBeNull()
    expect(parseRunEvent('{"done":true}')).toBeNull()
    expect(parseRunEvent('')).toBeNull()
  })
})

describe('PROJECT_NAME', () => {
  test('accepts Compose names and refuses anything with a slash, space or dollar sign', () => {
    expect(PROJECT_NAME.test('shop-database')).toBe(true)
    expect(PROJECT_NAME.test('my_app.v2')).toBe(true)
    expect(PROJECT_NAME.test('../etc')).toBe(false)
    expect(PROJECT_NAME.test('a b')).toBe(false)
    expect(PROJECT_NAME.test('$(id)')).toBe(false)
    expect(PROJECT_NAME.test('')).toBe(false)
  })
})

