// Pure helpers for the Compose projects: the project list from the container labels, the command
// lines pow/dock runs (never built from strings), the log lines of `docker compose logs`, and the
// NDJSON the run stream sends. No I/O here, so the unit tests use plain fixtures.

/** The labels Docker Compose puts on every container it creates. */
export const COMPOSE_LABELS = {
  project: 'com.docker.compose.project',
  workingDir: 'com.docker.compose.project.working_dir',
  configFiles: 'com.docker.compose.project.config_files',
  service: 'com.docker.compose.service',
} as const

/** The actions a project page can run. The client sends one of these names and nothing else. */
export const PROJECT_ACTIONS = ['up', 'stop', 'restart', 'pull', 'down', 'update-service'] as const
export type ProjectAction = (typeof PROJECT_ACTIONS)[number]

/** A project name as Compose writes it in the label (letters, digits, dots, dashes and underscores). */
export const PROJECT_NAME = /^[A-Za-z0-9][A-Za-z0-9_.-]{0,127}$/
/** A service name as Compose writes it in the label. The server still checks it is one of the project's services. */
export const SERVICE_NAME = /^[A-Za-z0-9][A-Za-z0-9_.-]{0,127}$/

/** A config file that is generated by another tool sits in a folder with this name. */
const GENERATED_FOLDER = '/.generated/'
/** How many lines of a config file are read for the "generated" check. */
export const HEAD_LINES = 5
/** A config file bigger than this is not read or saved (a Compose file is a few kilobytes). */
export const MAX_CONFIG_BYTES = 512 * 1024
/** How many past lines the merged project logs start with. */
export const PROJECT_LOG_TAIL = 200

/** The Compose project facts of one container: its labels and its state. */
export interface ComposeEntry {
  labels: Readonly<Record<string, string>>
  running: boolean
  /** true for the container pow/dock runs in */
  isSelf: boolean
}

/** A project as the containers show it, before the config files are read. */
export interface ProjectBase {
  name: string
  workingDir: string
  configFiles: string[]
  services: string[]
  running: number
  total: number
  containsSelf: boolean
}

/** The config files of a project: the comma-separated label, split into absolute paths. */
export function parseConfigFiles(value: string | undefined): string[] {
  if (!value) return []
  return value
    .split(',')
    .map((part) => part.trim())
    .filter((part) => part !== '')
}

/**
 * The projects of the containers, by name (sorted). A container without a project label is not a
 * project. The working folder and the config files come from the first container that has them.
 */
export function groupProjects(entries: readonly ComposeEntry[]): ProjectBase[] {
  const byName = new Map<string, ProjectBase & { serviceSet: Set<string> }>()
  for (const entry of entries) {
    const name = entry.labels[COMPOSE_LABELS.project]
    if (!name) continue
    let project = byName.get(name)
    if (!project) {
      project = {
        name,
        workingDir: '',
        configFiles: [],
        services: [],
        running: 0,
        total: 0,
        containsSelf: false,
        serviceSet: new Set<string>(),
      }
      byName.set(name, project)
    }
    project.total += 1
    if (entry.running) project.running += 1
    if (entry.isSelf) project.containsSelf = true
    if (!project.workingDir) project.workingDir = entry.labels[COMPOSE_LABELS.workingDir] ?? ''
    if (project.configFiles.length === 0)
      project.configFiles = parseConfigFiles(entry.labels[COMPOSE_LABELS.configFiles])
    const service = entry.labels[COMPOSE_LABELS.service]
    if (service) project.serviceSet.add(service)
  }
  return [...byName.values()]
    .map(({ serviceSet, ...project }) => ({ ...project, services: [...serviceSet].sort() }))
    .sort((a, b) => a.name.localeCompare(b.name))
}

/** The first lines of a text, joined back with newlines. Used for the "generated" check. */
export function firstLines(text: string, count: number = HEAD_LINES): string {
  return text.split(/\r?\n/).slice(0, count).join('\n')
}

/** True when a config file looks generated: it is in a `.generated` folder, or its first lines say so. */
export function isGeneratedConfig(path: string, head: string | null): boolean {
  if (path.includes(GENERATED_FOLDER)) return true
  if (head === null) return false
  return /generated|do not edit/i.test(head)
}

/** Compose argument lists: `-f` for each config file, placed after the project name. */
function composePrefix(name: string, configFiles: readonly string[]): string[] {
  return ['docker', 'compose', '-p', name, ...configFiles.flatMap((file) => ['-f', file])]
}

/**
 * The steps of an action, each one a full argv. Pull & update is two steps: pull, then up. A step
 * that fails stops the list (see the run route). `volumes` only applies to down. `service` only applies to
 * update-service: it pulls that one service and starts it again.
 */
export function actionSteps(
  name: string,
  configFiles: readonly string[],
  action: ProjectAction,
  volumes: boolean,
  service: string | null = null,
): string[][] {
  const prefix = composePrefix(name, configFiles)
  const up = [...prefix, 'up', '-d', '--remove-orphans']
  switch (action) {
    case 'update-service':
      if (service === null) return []
      return [
        [...prefix, 'pull', service],
        [...prefix, 'up', '-d', service],
      ]
    case 'up':
      return [up]
    case 'stop':
      return [[...prefix, 'stop']]
    case 'restart':
      return [[...prefix, 'restart']]
    case 'pull':
      return [[...prefix, 'pull'], up]
    case 'down':
      return [volumes ? [...prefix, 'down', '--volumes'] : [...prefix, 'down']]
  }
}

/** The argv of the merged logs: every service, the last lines first, with timestamps and no colors. */
export function logsArgv(name: string, configFiles: readonly string[], tail: number): string[] {
  return [...composePrefix(name, configFiles), 'logs', '-f', `--tail=${tail}`, '--no-color', '--timestamps']
}

/** The title of the run panel: the command the user sees. */
export function actionTitle(action: ProjectAction, volumes: boolean, service: string | null = null): string {
  switch (action) {
    case 'update-service':
      return `docker compose pull ${service ?? ''}, then up -d ${service ?? ''}`.trim()
    case 'up':
      return 'docker compose up'
    case 'stop':
      return 'docker compose stop'
    case 'restart':
      return 'docker compose restart'
    case 'pull':
      return 'docker compose pull, then up'
    case 'down':
      return volumes ? 'docker compose down --volumes' : 'docker compose down'
  }
}

export type RunRequest =
  { ok: true; action: ProjectAction; volumes: boolean; service: string | null } | { ok: false; error: string }

/**
 * The body of the run request: `{ "action": ... }`, plus `"volumes": true` for down only, and
 * `"service": "web"` for update-service only. Any other field is refused, so the client can never send
 * a path or an argument.
 */
export function parseRunBody(body: unknown): RunRequest {
  if (typeof body !== 'object' || body === null || Array.isArray(body)) {
    return { ok: false, error: 'Send { "action": "up" }.' }
  }
  const record = body as Record<string, unknown>
  const extra = Object.keys(record).filter((key) => !['action', 'volumes', 'service'].includes(key))
  if (extra.length > 0) return { ok: false, error: `Unknown field: ${extra[0]}.` }
  const action = record.action
  if (typeof action !== 'string' || !(PROJECT_ACTIONS as readonly string[]).includes(action)) {
    return { ok: false, error: `action must be one of: ${PROJECT_ACTIONS.join(', ')}.` }
  }
  const type = action as ProjectAction
  if (record.volumes !== undefined && typeof record.volumes !== 'boolean') {
    return { ok: false, error: 'volumes must be true or false.' }
  }
  if (record.volumes === true && type !== 'down') return { ok: false, error: 'volumes only applies to down.' }
  const volumes = record.volumes === true

  if (type === 'update-service') {
    if (typeof record.service !== 'string' || !SERVICE_NAME.test(record.service)) {
      return { ok: false, error: 'update-service needs a service name.' }
    }
    return { ok: true, action: type, volumes: false, service: record.service }
  }
  if (record.service !== undefined) return { ok: false, error: 'service only applies to update-service.' }
  return { ok: true, action: type, volumes, service: null }
}

/** One line of `docker compose logs`: "service-1  | 2026-... message". The service and the time are split off. */
export interface ComposeLogLine {
  service: string | null
  t: string | null
  m: string
}

const SERVICE_PART = /^[A-Za-z0-9][\w.-]*$/
const TIMESTAMP_PART = /^(\d{4}-\d{2}-\d{2}T\S+)\s(.*)$/

export function parseComposeLogLine(line: string): ComposeLogLine {
  let service: string | null = null
  let rest = line
  const separator = line.indexOf(' | ')
  if (separator > 0) {
    const candidate = line.slice(0, separator).trim()
    if (SERVICE_PART.test(candidate)) {
      service = candidate
      rest = line.slice(separator + 3)
    }
  }
  const stamped = TIMESTAMP_PART.exec(rest)
  if (stamped) return { service, t: stamped[1] ?? null, m: stamped[2] ?? '' }
  return { service, t: null, m: rest }
}

/** Splits text that arrives in pieces into whole lines. A line split across two pieces is kept until it ends. */
export function createLineSplitter(): { push(text: string): string[]; flush(): string[] } {
  let rest = ''
  return {
    push(text) {
      const combined = rest + text
      const parts = combined.split('\n')
      rest = parts.pop() ?? ''
      return parts.map((line) => line.replace(/\r$/, ''))
    },
    flush() {
      const last = rest.replace(/\r$/, '')
      rest = ''
      return last === '' ? [] : [last]
    },
  }
}

/** One event of the run stream: an output line, or the last event with the exit code. */
export type RunEvent = { s: 'out' | 'err'; m: string } | { done: true; code: number }

export function encodeRunEvent(event: RunEvent): string {
  return `${JSON.stringify(event)}\n`
}

/** Reads one NDJSON line of the run stream. Blank and unknown lines give null. */
export function parseRunEvent(line: string): RunEvent | null {
  const trimmed = line.trim()
  if (!trimmed) return null
  let parsed: unknown
  try {
    parsed = JSON.parse(trimmed)
  } catch {
    return null
  }
  if (typeof parsed !== 'object' || parsed === null) return null
  const record = parsed as Record<string, unknown>
  if (record.done === true && typeof record.code === 'number') return { done: true, code: record.code }
  if ((record.s === 'out' || record.s === 'err') && typeof record.m === 'string') return { s: record.s, m: record.m }
  return null
}

/** Reads a run stream chunk by chunk and returns the events that are complete. */
export function createRunReader(): { push(text: string): RunEvent[] } {
  const splitter = createLineSplitter()
  return {
    push(text) {
      const events: RunEvent[] = []
      for (const line of splitter.push(text)) {
        const event = parseRunEvent(line)
        if (event) events.push(event)
      }
      return events
    },
  }
}

/** The argv that checks a Compose file: `docker compose -p <name> -f ... config --quiet`. Nothing is started. */
export function configCheckArgv(name: string, configFiles: readonly string[]): string[] {
  return [...composePrefix(name, configFiles), 'config', '--quiet']
}

/**
 * The line number in a Compose error message, or null when the message has none. Two forms are read:
 * "yaml: line 4: ..." and go-yaml's "at L4.C2-L4.C9".
 */
export function composeErrorLine(message: string): number | null {
  const match = /\bline (\d+)\b/i.exec(message) ?? /\bL(\d+)\.C\d+/.exec(message)
  if (!match) return null
  const line = Number(match[1])
  return Number.isSafeInteger(line) && line > 0 ? line : null
}
